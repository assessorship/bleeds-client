const { customEntries, customSections } = Vencord.Plugins.plugins.Settings as any as typeof SettingsPlugin;

customEntries.push({
    key: "BLEEDS_BLEEDS_settings",
    title: "Bleeds Client Settings",
    Component: SettingsUi,
    Icon: VesktopSettingsIcon
});

customSections.push(() => ({
    section: "BleedsSettings",
    label: "Bleeds Client Settings",
    element: SettingsUi,
    className: "vc-Bleeds Client-settings"
}));

